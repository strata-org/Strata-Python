RECV = {"list": "xs", "dict": "d", "set": "s", "tuple": "t",
        "range": "rg", "str": "w"}


def method_lines():
    setup = {
        "list": ["xs = [1, 2]"],
        "dict": ['d = {"k": 1}'],
        "set": ["s = {1, 2}", "s2 = {2, 3}"],
        "tuple": ["t = (1, 2)"],
        "range": ["rg = range(4)"],
        "str": ['w = "aWb,c"'],
    }
    lines, i = [], 0
    for tag, ms in METHOD_ARGS.items():
        for m, a in ms:
            lines.append(f"def method_{tag}_{m}_{i}():")
            lines.extend(f"    {statement}" for statement in setup[tag])
            lines.extend([
                f"    m{i} = {RECV[tag]}.{m}({a})",
                "",
                "",
            ])
            i += 1
    return lines


