"""Generator for the accept-side matrices: the operator pair table
(lhs tag x rhs tag x op family, one line per cell), the three-way
method-policy arms per builtin type, and the builtin-call battery.
Regenerate with `python3 gen_pairs.py`.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
H = "# generated by gen_pairs.py; regenerate rather than edit\n"

VALS = {
    "int": "3", "float": "1.5", "bool": "True", "str": '"ab"',
    "list": "[1]", "tuple": "(1,)", "set": "{1}",
    "dict": '{"k": 1}', "none": "None",
}

# One concrete witness for every builtin tag pair and supported operator.
# The regression runner executes every RHS with CPython and requires that
# completion to occur in the analyzer's (possibly broader) residual.
OPS = {"add": "+", "sub": "-", "mul": "*", "div": "/",
       "floordiv": "//", "mod": "%", "pow": "**",
       "lshift": "<<", "rshift": ">>", "and": "&", "xor": "^", "or": "|"}
TAGS = ["int", "float", "bool", "str", "list", "tuple", "set", "dict",
        "none"]


def binop_lines():
    lines, i = [], 0
    for op, sym in OPS.items():
        for lt in TAGS:
            for rt in TAGS:
                lines.extend([
                    f"def matrix_{op}_{i}():",
                    f"    c{i} = {VALS[lt]} {sym} {VALS[rt]}",
                    "",
                    "",
                ])
                i += 1
    return lines


