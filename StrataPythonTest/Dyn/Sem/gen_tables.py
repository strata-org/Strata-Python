#!/usr/bin/env python3
"""Write the names of the built-in types' attribute tables, as CPython 3.12 has them.

Writes `StrataPython/Dyn/Sem/Generated/Names.lean`: for each built-in type of
`Generated/Types.lean` (the constants that `gen_types.py` writes), every name of CPython 3.12's
`vars(T)`, in its order, with the kind of its value: a slot wrapper, a method descriptor, a class
method descriptor, a built-in method (such as `object.__new__`), a getset or member descriptor, a
Python function, a `classmethod`, `staticmethod` or `property` object, or a plain value (`None`, a
`str`, an `int`); and whether CPython refuses to make an instance of `T`.  The rules fill the entries they model; every other entry is a gap.

It also writes `StrataPythonTest/Dyn/Sem/HasattrSamples.lean`, the samples of the `hasattr` test:
for a sample value of each kind, made by a few instructions of the IR, every name of `dir(x)` and
`dir(type(x))` with CPython's `hasattr(x, name)`.

Run it with CPython 3.12, from the package root:

    python3.12 StrataPythonTest/Dyn/Sem/gen_tables.py

Any other version is refused: the names are 3.12's.
"""

import sys
import types
from pathlib import Path

if sys.version_info[:2] != (3, 12):
    sys.exit(f"gen_tables.py needs CPython 3.12, not {sys.version.split()[0]}")

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_types  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "StrataPython/Dyn/Sem/Generated/Names.lean"
SAMPLES_OUT = ROOT / "StrataPythonTest/Dyn/Sem/HasattrSamples.lean"

# The samples of the `hasattr` test: a label, the value, and the instructions of the IR that make
# it as `%x.0` (`^err.0()` raises to the test's handler).
SAMPLES = [
    ("int", 1, '%x.0 : py.Value = py.intLit(1)'),
    ("bool", True, '%x.0 : py.Value = py.boolLit(true)'),
    ("float", 1.5, '%x.0 : py.Value = py.floatLit(1.5)'),
    ("str", "a", '%x.0 : py.Value = py.strLit("a")'),
    ("bytes", b"a", '%x.0 : py.Value = py.bytesLit("a")'),
    ("None", None, '%x.0 : py.Value = py.noneLit'),
    ("tuple", (1,), '%a.0 : py.Value = py.intLit(1)\n%x.0 : py.Value = py.mkTuple(%a.0)'),
    ("list", [1], '%a.0 : py.Value = py.intLit(1)\n%x.0 : py.Value = py.mkList(%a.0)'),
    ("dict", {}, '%x.0 : py.Value = py.mkDict ^err.0()'),
    ("set", {1}, '%a.0 : py.Value = py.intLit(1)\n%x.0 : py.Value = py.mkSet(%a.0) ^err.0()'),
    ("the class int", int, '%x.0 : py.Value = py.loadGlobal("m", "int") ^err.0()'),
    ("the class object", object, '%x.0 : py.Value = py.loadGlobal("m", "object") ^err.0()'),
    ("the class type", type, '%x.0 : py.Value = py.loadGlobal("m", "type") ^err.0()'),
    ("the function len", len, '%x.0 : py.Value = py.loadGlobal("m", "len") ^err.0()'),
]

# The kind of each attribute value, by its type, as `AttrKind`'s constructor names it.
KINDS = {
    types.WrapperDescriptorType: "slotWrapper",
    types.MethodDescriptorType: "method",
    types.ClassMethodDescriptorType: "classMethodDescr",
    types.BuiltinFunctionType: "builtinMethod",
    types.GetSetDescriptorType: "getset",
    types.MemberDescriptorType: "member",
    types.FunctionType: "pyFunction",
    classmethod: "classMethod",
    staticmethod: "staticMethod",
    property: "property",
    type(None): "noneValue",
    str: "strValue",
    int: "intValue",
}


def kind_of(v):
    k = KINDS.get(type(v))
    if k is None:
        raise SystemExit(f"no AttrKind for a value of type {type(v).__qualname__}")
    return k


def main():
    order, entries = gen_types.collect()
    lines = [
        "/-",
        "  Copyright Strata Contributors",
        "",
        "  SPDX-License-Identifier: Apache-2.0 OR MIT",
        "-/",
        "module",
        "public import StrataPython.Dyn.Sem.Generated.Types",
        "",
        "set_option autoImplicit false",
        "",
        "/-!",
        "# The names of the built-in types' attribute tables (generated)",
        "",
        f"Generated by `StrataPythonTest/Dyn/Sem/gen_tables.py` from CPython {sys.version.split()[0]}.",
        "Do not edit: run the script again.",
        "",
        "`Builtin.ownNames T` gives every name of `vars(T)` for a built-in type `T`, in CPython's",
        "order, with the kind of its value; it is empty for a constant that is not a type.",
        "`Builtin.noInstances T` says whether CPython refuses to make an instance of `T`.",
        "-/",
        "",
        "namespace StrataPython.Dyn.Sem",
        "",
        "/-- The kind of the value of a built-in type's attribute. -/",
        "public inductive AttrKind where",
        "  /-- A slot wrapper, such as `object.__eq__`. -/",
        "  | slotWrapper",
        "  /-- A method descriptor, such as `list.append`. -/",
        "  | method",
        "  /-- A class method descriptor, such as `dict.fromkeys`. -/",
        "  | classMethodDescr",
        "  /-- A built-in method of the type, such as `object.__new__`. -/",
        "  | builtinMethod",
        "  /-- A getset descriptor, such as `type.__name__`. -/",
        "  | getset",
        "  /-- A member descriptor, such as `BaseException.__suppress_context__`. -/",
        "  | member",
        "  /-- A Python function. -/",
        "  | pyFunction",
        "  | classMethod",
        "  | staticMethod",
        "  | property",
        "  /-- The value `None`, such as `list.__hash__`. -/",
        "  | noneValue",
        "  /-- A `str`, such as a `__doc__`. -/",
        "  | strValue",
        "  /-- An `int`. -/",
        "  | intValue",
        "  deriving DecidableEq, Repr, Inhabited",
        "",
        "@[expose] public section",
        "",
        "/-- Every name of `vars(T)` for the built-in type `T`, in CPython 3.12's order, with the kind",
        "of its value; empty for a constant that is not a type. -/",
        "def Builtin.ownNames : Builtin → Array (String × AttrKind)",
    ]
    for k in order:
        kind, obj = entries[k]
        if kind != "type":
            continue
        names = ", ".join(f"({gen_types.lean_str(n)}, .{kind_of(v)})" for n, v in vars(obj).items())
        lines.append(f"  | .{gen_types.lean_ident(k)} => #[{names}]")
    lines += [
        "  | _ => #[]",
        "",
        "/-- Whether CPython 3.12 refuses to make an instance of the built-in type `T`",
        "(`Py_TPFLAGS_DISALLOW_INSTANTIATION`): a static type with no `tp_new`, such as",
        "`builtin_function_or_method`. -/",
        "def Builtin.noInstances : Builtin → Bool",
    ]
    for k in order:
        kind, obj = entries[k]
        if kind == "type" and obj.__flags__ & (1 << 7):
            lines.append(f"  | .{gen_types.lean_ident(k)} => true")
    lines += [
        "  | _ => false",
        "",
        "end",
        "",
        "end StrataPython.Dyn.Sem",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    write_samples()


def write_samples():
    lines = [
        "/-",
        "  Copyright Strata Contributors",
        "",
        "  SPDX-License-Identifier: Apache-2.0 OR MIT",
        "-/",
        "module",
        "",
        "/-!",
        "# The samples of the `hasattr` test (generated)",
        "",
        f"Generated by `StrataPythonTest/Dyn/Sem/gen_tables.py` from CPython {sys.version.split()[0]}.",
        "Do not edit: run the script again.",
        "",
        "Each sample: a label, the instructions of the IR that make the value as `%x.0`, and every",
        "name of `dir(x)` and `dir(type(x))` with the type name of `getattr(x, name)` where CPython's",
        "`hasattr(x, name)` holds, and `none` where it doesn't.",
        "-/",
        "",
        "namespace StrataPython.Dyn.Sem.HasattrSamples",
        "",
        "/-- The samples, in order. -/",
        "public def samples : Array (String × String × Array (String × Option String)) := #[",
    ]
    rows = []
    for label, x, ir in SAMPLES:
        names = sorted(set(dir(x)) | set(dir(type(x))))
        def entry(n):
            if not hasattr(x, n):
                return f"({gen_types.lean_str(n)}, none)"
            return f"({gen_types.lean_str(n)}, some {gen_types.lean_str(type(getattr(x, n)).__name__)})"
        pairs = ", ".join(entry(n) for n in names)
        rows.append(f"  ({gen_types.lean_str(label)}, {gen_types.lean_str(ir)}, #[{pairs}])")
    lines.append(",\n".join(rows))
    lines += ["]", "", "end StrataPython.Dyn.Sem.HasattrSamples", ""]
    SAMPLES_OUT.write_text("\n".join(lines))
    print(f"wrote {SAMPLES_OUT}")


if __name__ == "__main__":
    main()
