"""Write `SumCases.lean`: CPython 3.12's `sum` of ints, bools and floats.

    python3.12 StrataPythonTest/Dyn/Sem/Library/gen_sum_cases.py \
        > StrataPythonTest/Dyn/Sem/Library/SumCases.lean

Each case is a start, the items and CPython's result. The start is `-` (none), `s`, `y` or `a`
(a `str`, `bytes` or `bytearray`), or one value; the items are values separated by spaces. A
value is `i:<n>` (an int), `b:<n>` (a bool), `I:<n>` (an instance of a subclass of `int`),
`f:<bits>` (a float, by its bits) or `F:<bits>` (an instance of a subclass of `float`). The
result is `i<n>`, `b<n>` (a bool), `f<bits>`, `fnan` for any NaN, or `E<class>: <message>`.
"""
import math
import random
import struct
import sys

assert sys.version_info[:2] == (3, 12), "run with CPython 3.12"


class I(int):
    pass


class F(float):
    pass


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def value(tok):
    kind, v = tok.split(":")
    if kind == "i":
        return int(v)
    if kind == "b":
        return bool(int(v))
    if kind == "I":
        return I(int(v))
    x = struct.unpack("<d", struct.pack("<Q", int(v)))[0]
    return x if kind == "f" else F(x)


def result(start, items):
    args = [value(t) for t in items]
    try:
        if start == "-":
            r = sum(args)
        else:
            r = sum(args, {"s": "", "y": b"", "a": bytearray()}.get(start) if start in "sya"
                    else value(start))
    except Exception as e:
        return f"E{type(e).__name__}: {e}"
    if isinstance(r, float):
        return "fnan" if math.isnan(r) else f"f{bits(r)}"
    if isinstance(r, bool):
        return f"b{int(r)}"
    return f"i{int(r)}"


INTS = [0, 1, -1, 2, 7, -12, 2 ** 30, 2 ** 53 + 1, 2 ** 62, 2 ** 63 - 1, -2 ** 63, 2 ** 63,
        -2 ** 63 - 1, 2 ** 64, 3 ** 50, 2 ** 1024]
FLOATS = [0.1, 0.2, 0.3, 0.7, 1.0, -1.0, 0.0, -0.0, 1e16, -1e16, 1e100, -1e100, 1e308, -1e308,
          5e-324, 2.0 ** 53, 0.5, math.inf, -math.inf, math.nan, 1 / 3, 2 / 3]


def rand_value(rng):
    k = rng.random()
    if k < 0.45:
        x = rng.choice(FLOATS) if rng.random() < 0.6 else rng.uniform(-10, 10) * 10.0 ** rng.randint(-20, 20)
        return f"{'F' if rng.random() < 0.08 else 'f'}:{bits(x)}"
    if k < 0.9:
        n = rng.choice(INTS) if rng.random() < 0.7 else rng.randint(-10 ** 6, 10 ** 6)
        n = n if rng.random() < 0.8 else -n
        return f"{'I' if rng.random() < 0.1 else 'i'}:{n}"
    return f"b:{rng.randint(0, 1)}"


FIXED = [
    ("-", []), ("-", ["f:" + str(bits(0.1))] * 10), ("f:" + str(bits(-0.0)), []),
    ("f:" + str(bits(-0.0)), ["f:" + str(bits(-0.0))]), ("-", ["f:" + str(bits(-0.0))]),
    # An int that doesn't fit in 64 bits ends the int phase, so the floats after it are added
    # without compensation.
    ("i:" + str(2 ** 63), ["i:" + str(-2 ** 63)] + ["f:" + str(bits(0.1))] * 10),
    ("-", ["i:" + str(2 ** 63), "i:" + str(-2 ** 63)] + ["f:" + str(bits(0.1))] * 10),
    ("-", ["i:-1", "i:" + str(2 ** 63), "i:" + str(1 - 2 ** 63)] + ["f:" + str(bits(0.1))] * 10),
    ("-", ["i:" + str(2 ** 63 - 1), "i:1", "f:" + str(bits(0.1)), "f:" + str(bits(0.2))]),
    ("f:" + str(bits(1e100)), ["f:" + str(bits(1.0)), "f:" + str(bits(-1e100))]),
    ("f:" + str(bits(1e100)), ["i:1", "f:" + str(bits(-1e100))]),
    ("f:" + str(bits(math.inf)), ["f:" + str(bits(1.0))]), ("-", ["f:" + str(bits(1e308))] * 2 + ["f:" + str(bits(-1e308))]),
    ("f:" + str(bits(0.1)), ["i:" + str(2 ** 1024)]), ("s", []), ("y", ["i:1"]), ("a", []),
    ("b:1", ["i:1"]), ("b:1", []), ("F:" + str(bits(0.1)), ["f:" + str(bits(0.2))] * 3),
    ("-", ["F:" + str(bits(0.1))] + ["f:" + str(bits(0.1))] * 9),
    ("-", ["f:" + str(bits(0.1))] + ["F:" + str(bits(0.1))] + ["f:" + str(bits(0.1))] * 8),
    ("-", ["I:5", "f:" + str(bits(0.1))] + ["f:" + str(bits(0.1))] * 9),
    # The int phase ends when the total doesn't fit in 64 bits, though each item does.
    ("-", ["i:" + str(2 ** 62), "i:" + str(2 ** 62), "i:" + str(-2 ** 63)] + ["f:" + str(bits(0.1))] * 10),
    # The float phase takes an instance of a subclass of int, but not one of a subclass of float.
    ("-", ["f:" + str(bits(0.1))] * 5 + ["I:0"] + ["f:" + str(bits(0.1))] * 5),
    ("-", ["f:" + str(bits(0.1))] * 5 + ["F:0"] + ["f:" + str(bits(0.1))] * 5),
    ("b:1", []), ("b:0", ["b:1"]),
]


def cases():
    rng = random.Random(20261028)
    out = [(s, items, result(s, items)) for s, items in FIXED]
    starts = ["-"] * 6 + ["s", "y", "a", "b:0", "b:1"]
    for _ in range(1500):
        s = rng.choice(starts) if rng.random() < 0.6 else rand_value(rng)
        items = [rand_value(rng) for _ in range(rng.randrange(0, 12))]
        out.append((s, items, result(s, items)))
    return out


