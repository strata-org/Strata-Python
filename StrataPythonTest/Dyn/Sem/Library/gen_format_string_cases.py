"""Write `FormatStringCases.lean`: how CPython 3.12 reads format strings.

    python3.12 StrataPythonTest/Dyn/Sem/Library/gen_format_string_cases.py \
        > StrataPythonTest/Dyn/Sem/Library/FormatStringCases.lean

Three kinds of case, each a string and CPython's result written as text:
- `pieces`: `_string.formatter_parser(s)`, as a list of `L<text>` (adjacent literal text joined),
  `F<name>|<conversion>|<spec>` and, where the reading stops, `E<message>`, separated by
  newlines;
- `split`: `_string.formatter_field_name_split(s)`: the first part (`I<n>` or `S<text>`, or
  `E<message>`), then each accessor (`A<name>`, `N<n>` or `K<key>`) or `E<message>`;
- `number`: `s.format('a', 'b', 'c', x='X')` for a string whose fields have no accessor,
  conversion or spec, which shows the numbering of the fields: the result, or
  `E<class>: <message>`.
"""
import _string
import random
import sys

assert sys.version_info[:2] == (3, 12), "run with CPython 3.12"


def lean_str(s):
    out = []
    for c in s:
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif c == "\n":
            out.append("\\n")
        elif 0x20 <= ord(c) < 0x7f:
            out.append(c)
        elif ord(c) <= 0xFFFF:
            out.append(f"\\u{ord(c):04x}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def pieces(s):
    out = []
    try:
        for lit, name, spec, conv in _string.formatter_parser(s):
            if lit:
                if out and out[-1].startswith("L"):
                    out[-1] += lit
                else:
                    out.append("L" + lit)
            if name is not None:
                out.append(f"F{name}|{conv or ''}|{spec}")
    except ValueError as e:
        out.append(f"E{e}")
    return "\n".join(out)


def split(s):
    try:
        first, rest = _string.formatter_field_name_split(s)
    except ValueError as e:
        return f"E{e}"
    out = [f"I{first}" if isinstance(first, int) else f"S{first}"]
    try:
        for is_attr, v in rest:
            out.append(f"A{v}" if is_attr else (f"N{v}" if isinstance(v, int) else f"K{v}"))
    except ValueError as e:
        out.append(f"E{e}")
    return "\n".join(out)


def number(s):
    try:
        return s.format("a", "b", "c", x="X")
    except Exception as e:
        return f"E{type(e).__name__}: {e}"


FIXED = [
    "", "a", "{}", "{0}", "{x}", "{{", "}}", "{{}}", "a{{b}}c", "{", "}", "a{", "a}", "{0", "{0!",
    "{0!r", "{0!r}", "{0!r:", "{0!r:>5}", "{0!rx}", "{0:{1}}", "{0:{1}x{2}}", "{0:{{}}}", "{0:{",
    "{0[}", "{0[a]}", "{0[a:b!c]}", "{0[}]}", "{0.a.b[1][x]}", "{a{b}", "{!}", "{:}", "{!:}",
    "{٣}", "{0}{}", "{}{0}", "{}{x}{}", "{x}{}", "{9}", "{" + "9" * 20 + "}", "{0:{}}",
    "{0!\x00}", "{0!\x00:x}", "{0!\x00x}",
]
SPLIT_FIXED = [
    "", "0", "x", "0.a", "0[1]", "0[x]", "0[", "0[]", "0.", "0..a", "0[1]x", "0[1].a[b]", "٣",
    "9" * 20, "0[" + "9" * 20 + "]", "a.b.c", ".a", "[0]", "0[a]b", "x[1]y",
    "9" * 20 + "x", "0[" + "9" * 20 + "x]", "9223372036854775807", "9223372036854775808",
    "0[9223372036854775807]", "0[9223372036854775808]", "-1", "\u00b2", "0[\u00b2]",
    "\U0001d7d8", "0[\U0001d7d8]",
]

NUMBER_FIXED = ["", "a", "{}", "{}{}{}", "{}{}{}{}", "{0}{0}", "{}{0}", "{0}{}", "{x}{}", "{}{x}{}",
                "{y}", "{3}", "{٣}", "{{}}{}", "{}}", "{" + "9" * 20 + "}"]


def cases():
    rng = random.Random(20261028)
    pool = "{}!:[].0x1a ٣\x00\U0001d7d8rs"
    out = []
    strs = list(FIXED) + ["".join(rng.choice(pool) for _ in range(rng.randrange(1, 9)))
                          for _ in range(800)]
    for s in strs:
        out.append(("pieces", s, pieces(s)))
    for s in SPLIT_FIXED + ["".join(rng.choice("0x.[]1a-\U0001d7d8\u00b2") for _ in range(rng.randrange(0, 7)))
                            for _ in range(300)]:
        out.append(("split", s, split(s)))
    for s in NUMBER_FIXED + ["".join(rng.choice(["{}", "{0}", "{1}", "{x}", "{3}", "a", "{y}"])
                              for _ in range(rng.randrange(1, 5))) for _ in range(200)]:
        out.append(("number", s, number(s)))
    return out


