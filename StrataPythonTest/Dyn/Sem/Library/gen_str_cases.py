"""Write `StrCases.lean`: CPython 3.12's case methods and class tests of `str` on test strings.

    python3.12 StrataPythonTest/Dyn/Sem/Library/gen_str_cases.py \
        > StrataPythonTest/Dyn/Sem/Library/StrCases.lean

The strings are fixed examples (the final-sigma rule, special casings, titlecase letters) and
random strings over a pool of characters of every class that the methods treat apart.
"""
import random
import sys

assert sys.version_info[:2] == (3, 12), "run with CPython 3.12"

FIXED = [
    "", "a", "A", "hello world", "Hello World", "HELLO", "hELLO wORLD", "ΑΣ", "ΣΑ", "αΣ", "ΑΣ.",
    "Α'Σ", "ΑΣ'", "ΆΣ", "ΑΣ́", "Σ", "ΑΣΑ", "ΑΣ Α", "ΌΣΟΣ", "ß", "straße", "ǆ", "ǅ",
    "Ǆ", "ǆungla", "ŉ", "İstanbul", "ﬁ", "ﬃ", "ΐ", "ǰ", "Ά", "123", "١٢٣", "½", "Ⅻ", "x²", " ",
    "\t\n", "　", " ", "_a1", "1a", "a b", "é", "Éa", "ÉA", "ŉA", "ᾈ", "ᾀ", "ⅰ", "Ⓐ",
    "ꭰ", "ꭰꭰ", "\U0001d400", "\U0001e900", "ʰa", "aʰ", "Aʰ",
    # Characters that are both cased and case-ignorable, next to a capital sigma, and an astral
    # case-ignorable one.
    "ʰΣ", "ΑΣʰ", "ΑΣͅ", "ΑʰΣ", "ΑʰΣʰ", "Α\U000e0001Σ", "ΑΣ\U000e0001", "ΑΣ\U000e0001a",
]

POOL = (
    "aAzZßǅǆǄΣσςΑαΌὈᾈᾀİıŉﬁ" "ʰᵃ'.:­́ͅ" "09١٢½Ⅻ²" " \t　 _-é"
    "\U0001d400\U0001e900ꭰⓐⒶ"
)

METHODS = ["upper", "lower", "casefold", "swapcase", "capitalize", "title"]
TESTS = ["isalpha", "isdecimal", "isdigit", "isnumeric", "isalnum", "isspace", "isupper",
         "islower", "istitle", "isidentifier", "isprintable", "isascii"]


def lean_str(s):
    out = []
    for c in s:
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif 0x20 <= ord(c) < 0x7f:
            out.append(c)
        elif ord(c) <= 0xFFFF:
            out.append(f"\\u{ord(c):04x}")
        else:
            # Lean's `\u` escape takes four digits, so a character above U+FFFF stays as it is.
            out.append(c)
    return '"' + "".join(out) + '"'


def strings():
    rng = random.Random(20261028)
    out = list(FIXED)
    for _ in range(400):
        out.append("".join(rng.choice(POOL) for _ in range(rng.randrange(1, 9))))
    return out


