items = []
for s in strings():
    cs = ", ".join(lean_str(getattr(s, m)()) for m in METHODS)
    ts = ", ".join("true" if getattr(s, t)() else "false" for t in TESTS)
    items.append(f"  {{ s := {lean_str(s)}, cases := [{cs}],\n    tests := [{ts}] }}")
print(",\n".join(items))
