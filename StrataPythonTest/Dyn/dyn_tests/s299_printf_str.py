# Test: printf-style % of a str format: conversions, flags, width, precision, * and mapping keys, and their errors
def t(fmt, args):
    try:
        r = fmt % args
        print(repr(r))
    except Exception as e:
        print(type(e).__name__, e)
t("%s %r %a", ("é", "é", "é"))
t("%5d|%-5d|%05d|%+d|% d", (42, 42, 42, 42, 42))
t("%x %X %#x %#X %o %#o %#08x", (255, 255, 255, 255, 8, 8, 255))
t("%.3d %.0d %5.3d", (7, 0, -7))
t("%f %.2f %e %E %g %G %#.0f %10.3f %-10.2e|", (3.14159, 2.5, 12345.678, 0.0001, 1e20, 1e-5, 2.0, -1.5, 99.0))
t("%c%c", (65, "z"))
t("%*d|%-*d|%.*f", (5, 1, 4, 2, 2, 3.14159))
t("%(a)s and %(b)d", {"a": "x", "b": 3})
t("%s", (1, 2))
t("%s %s", (1,))
t("%d", "x")
t("%d", 2.7)
t("%x", 2.5)
t("%q", 1)
t("%", 1)
t("%5", 1)
t("%(a", {"a": 1})
t("%(a)s", 5)
t("abc", 5)
t("abc", [5])
t("%%%s%%", 5)
t("%s", [1, 2])
t("%c", 0x110000)
t("%c", "ab")
t("%.2s|%5s|%-5s|", ("hello", "ab", "ab"))
t("%i %u", (True, False))
t("%r", ("a'b",))
t("%5%", ())
t("%ld %hd", (1, 2))
